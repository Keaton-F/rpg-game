def set_level(character, level):
    """
    Повышает уровень персонажа до указанного значения.

    Повышение происходит через обычный метод level_up(), поэтому
    все изменения характеристик выполняются по правилам игры.

    Аргументы:
        character (Character): персонаж, уровень которого нужно изменить.
        level (int): целевой уровень персонажа.

    Возвращает:
        None: изменяет уровень и характеристики персонажа напрямую.
    """
    while character.lvl < level:
        character.level_up()
